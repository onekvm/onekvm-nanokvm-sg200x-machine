"""Regenerate the checked-in splash artwork; not needed on target or by OE."""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
BACKGROUND = (8, 11, 17)
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
CJK_FONT = "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"
ASSETS = []
IMAGES = {}


def rgb565(pixel):
    r, g, b = pixel
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def add(name, image):
    assert 0 < image.width <= 320 and 0 < image.height <= 172
    data = image.tobytes()
    pixels = [rgb565(data[i:i + 3]) for i in range(0, len(data), 3)]
    runs = []
    for pixel in pixels:
        if runs and runs[-1][1] == pixel and runs[-1][0] < 65535:
            runs[-1][0] += 1
        else:
            runs.append([1, pixel])
    ASSETS.append((name, image.width, image.height, runs))
    IMAGES[name] = image


def label(name, text, size, color, language="en"):
    font = ImageFont.truetype(FONT if language == "en" else CJK_FONT, size, index=0 if language == "en" else (3 if language == "zh_tw" else 2))
    left, top, right, bottom = font.getbbox(text)
    image = Image.new("RGB", (right - left, bottom - top), BACKGROUND)
    ImageDraw.Draw(image).text((-left, -top), text, font=font, fill=color)
    add(name, image)


logo = Image.open(HERE / "logo.png").convert("RGBA")
logo = logo.crop(logo.getbbox())
for name, width in (("logo_boot", 228), ("logo_install", 200)):
    mark = logo.resize(
        (width, round(width * logo.height / logo.width)), Image.Resampling.LANCZOS
    )
    image = Image.new("RGB", mark.size, BACKGROUND)
    image.paste(mark, (0, 0), mark)
    add(name, image)

TRANSLATIONS = {
    "en": (
        "Starting up", "Installing system", "Do not power off or remove the SD card",
        "Setup paused", "Check the serial console for details",
        ("Preparing system files", "Saving boot files", "Preparing storage", "Restoring boot files",
         "Installing system files", "Preparing data storage", "Finishing up"),
    ),
    "zh": (
        "正在启动", "正在安装系统", "请勿断电或拔出 SD 卡", "安装已暂停", "请查看串口日志了解详情",
        ("准备系统文件", "保存启动文件", "准备存储空间", "恢复启动文件", "安装系统文件", "准备数据分区", "完成安装"),
    ),
    "zh_tw": (
        "正在啟動", "正在安裝系統", "請勿斷電或拔出 SD 卡", "安裝已暫停", "請查看序列埠記錄瞭解詳情",
        ("準備系統檔案", "儲存啟動檔案", "準備儲存空間", "還原啟動檔案", "安裝系統檔案", "準備資料分割區", "完成安裝"),
    ),
}
for language, (starting, installing, warning, paused, error_detail, stages) in TRANSLATIONS.items():
    for name, text, size, color in (
        ("starting", starting, 12, (132, 144, 164)),
        ("installing", installing, 14, (234, 238, 245)),
        ("warning", warning, 10, (132, 144, 164)),
        ("paused", paused, 14, (234, 238, 245)),
        ("error_detail", error_detail, 11, (132, 144, 164)),
    ):
        label(f"{language}_{name}", text, size, color, language)
    for index, text in enumerate(stages, 1):
        label(f"{language}_stage_{index}", text, 11, (132, 144, 164), language)

lines = [
    "/* SPDX-License-Identifier: MIT */",
    "/* Generated by generate-assets.py; RGB565 run-length encoded artwork. */",
]
for name, width, height, runs in ASSETS:
    lines.append(f"static const uint16_t {name}_runs[] = {{")
    for offset in range(0, len(runs), 6):
        lines.append("    " + ", ".join(f"{n}, 0x{c:04x}" for n, c in runs[offset:offset + 6]) + ",")
    lines.extend(
        (
            "};",
            f"static const struct splash_asset {name} = {{",
            f"    {width}, {height}, {name}_runs, sizeof({name}_runs) / sizeof(uint16_t)",
            "};",
        )
    )
for language in TRANSLATIONS:
    lines.extend((
        f"static const struct splash_labels labels_{language} = {{",
        "    " + ", ".join(f"&{language}_{name}" for name in ("starting", "installing", "warning", "paused", "error_detail")) + ",",
        "    { " + ", ".join(f"&{language}_stage_{i}" for i in range(1, 8)) + " },",
        "};",
    ))
(HERE / "assets.h").write_text("\n".join(lines) + "\n")
print(f"Wrote {len(ASSETS)} assets to {HERE / 'assets.h'}")

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--uboot-header", type=Path)
args = parser.parse_args()
if args.uboot_header:
    frame = Image.new("RGB", (320, 172), BACKGROUND)
    for name, y in (("logo_boot", 48), ("en_starting", 125)):
        art = IMAGES[name]
        frame.paste(art, ((320 - art.width) // 2, y))
    # The Desk's native panel is 172x320; wire pixels are RGB565, MSB first.
    pixels = [rgb565(p) for p in frame.transpose(Image.Transpose.ROTATE_90).getdata()]
    runs = []
    for pixel in pixels:
        if runs and runs[-1][1] == pixel and runs[-1][0] < 65535:
            runs[-1][0] += 1
        else:
            runs.append([1, pixel])
    header = ["/* SPDX-License-Identifier: GPL-2.0+ */",
              "/* Generated by onekvm-nanokvm-machine/boot-splash/generate-assets.py. */",
              "static const u16 onekvm_logo_runs[] = {"]
    for offset in range(0, len(runs), 6):
        header.append("\t" + ", ".join(f"{n}, 0x{c:04x}" for n, c in runs[offset:offset + 6]) + ",")
    header.append("};")
    args.uboot_header.write_text("\n".join(header) + "\n")
    print(f"Wrote OneKVM U-Boot artwork to {args.uboot_header}")
